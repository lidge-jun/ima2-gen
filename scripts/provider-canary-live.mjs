#!/usr/bin/env node
/**
 * Billing provider canary (#152, weekly and pre-release tiers).
 *
 * The no-cost canary in provider-canary.mjs probes model lists, so it sees a
 * provider renaming an endpoint but not a provider changing what generation
 * actually returns. This one issues real generation requests, which means it
 * costs real money. That is why nothing schedules it: provider-canary-live.yml
 * is workflow_dispatch only and sits behind the provider-canary-live
 * environment.
 *
 * Tiers:
 *   weekly       one image per credentialed lane, fixed prompt
 *   pre-release  two representative lanes, generate + edit each
 *
 * Result bytes are never written to disk (#152: "결과 이미지는 장기 저장하지
 * 않는다"). Only status, HTTP code, latency, and response shape are recorded.
 *
 * A lane without a credential is "skip", never "pass" — the same rule the
 * no-cost canary uses, for the same reason: a green run over zero coverage is
 * a lie.
 */
import { appendFileSync } from "node:fs";

const TIMEOUT_MS = 180_000;
const PROMPT = "A single matte ceramic mug on a plain light grey background, centered, soft even lighting";
const EDIT_PROMPT = "Change the mug color to deep navy blue, keep everything else identical";

/** 1x1 transparent PNG, used as the edit input so no generated byte is stored. */
const TINY_PNG_B64 =
  "iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mP8z8BQDwAEhQGAhKmMIQAAAABJRU5ErkJggg==";

/** Never let a key, token, or credential-bearing URL reach the log. */
export function redact(message) {
  return String(message ?? "")
    .replace(/(sk|xai|apikey)-[A-Za-z0-9_-]+/g, "$1-REDACTED")
    .replace(/AI[A-Za-z0-9_-]{20,}/g, "AI-REDACTED")
    .replace(/([?&](?:key|api_key|access_token)=)[^&\s]+/gi, "$1REDACTED")
    .slice(0, 300);
}

/**
 * Describes a response without keeping it. Image payloads are multi-megabyte
 * base64; recording their shape is the whole point and recording their bytes
 * is what #152 forbids.
 */
export function describeShape(body) {
  if (body === null || body === undefined) return "empty";
  if (Array.isArray(body)) return `array[${body.length}]`;
  if (typeof body !== "object") return typeof body;
  const keys = Object.keys(body).sort();
  const imageCount = Array.isArray(body.data) ? body.data.length : null;
  return imageCount === null ? `object{${keys.join(",")}}` : `object{${keys.join(",")}} data[${imageCount}]`;
}

async function postJson(url, headers, payload) {
  const startedAt = Date.now();
  const res = await fetch(url, {
    method: "POST",
    headers: { "content-type": "application/json", ...headers },
    body: JSON.stringify(payload),
    signal: AbortSignal.timeout(TIMEOUT_MS),
  });
  const latencyMs = Date.now() - startedAt;
  let body = null;
  try {
    body = await res.json();
  } catch {
    return { httpStatus: res.status, latencyMs, shape: "non-json" };
  }
  return { httpStatus: res.status, latencyMs, shape: describeShape(body) };
}

/**
 * Lane probes. Each returns { status, httpStatus, latencyMs, shape } or a skip.
 * Endpoints mirror the runtime adapters; tests/provider-canary-live-contract
 * checks the file never schedules itself, and the no-cost canary's parity test
 * already guards the shared auth surfaces.
 */
export const LIVE_LANES = {
  api: {
    env: "CANARY_OPENAI_API_KEY",
    async generate(key) {
      const out = await postJson("https://api.openai.com/v1/images/generations", { Authorization: `Bearer ${key}` }, {
        model: "gpt-image-2", prompt: PROMPT, n: 1, size: "1024x1024",
      });
      return out;
    },
    async edit(key) {
      const out = await postJson("https://api.openai.com/v1/images/edits", { Authorization: `Bearer ${key}` }, {
        model: "gpt-image-2", prompt: EDIT_PROMPT, image: `data:image/png;base64,${TINY_PNG_B64}`, n: 1, size: "1024x1024",
      });
      return out;
    },
  },
  "grok-api": {
    env: "CANARY_XAI_API_KEY",
    async generate(key) {
      return postJson("https://api.x.ai/v1/images/generations", { Authorization: `Bearer ${key}` }, {
        model: "grok-2-image", prompt: PROMPT, n: 1,
      });
    },
    async edit(key) {
      return postJson("https://api.x.ai/v1/images/generations", { Authorization: `Bearer ${key}` }, {
        model: "grok-2-image", prompt: EDIT_PROMPT, n: 1,
      });
    },
  },
  "gemini-api": {
    env: "CANARY_GEMINI_API_KEY",
    async generate(key) {
      return postJson(
        "https://generativelanguage.googleapis.com/v1beta/models/gemini-3-pro-image-preview:generateContent",
        { "x-goog-api-key": key },
        { contents: [{ parts: [{ text: PROMPT }] }] },
      );
    },
  },
  atlascloud: {
    env: "CANARY_ATLASCLOUD_API_KEY",
    async generate(key) {
      return postJson("https://api.atlascloud.ai/api/v1/images/generations", { Authorization: `Bearer ${key}` }, {
        model: "openai/gpt-image-2/text-to-image", prompt: PROMPT, n: 1,
      });
    },
  },
  minimax: {
    env: "CANARY_MINIMAX_API_KEY",
    async generate(key) {
      const base = process.env.CANARY_MINIMAX_BASE_URL || "https://api.minimax.io/v1";
      return postJson(`${base.replace(/\/+$/, "")}/image_generation`, { Authorization: `Bearer ${key}` }, {
        model: "image-01", prompt: PROMPT, n: 1,
      });
    },
  },
};

/** pre-release exercises the two lanes that carry the most product surface. */
export const PRE_RELEASE_LANES = ["api", "grok-api"];

export function lanesForTier(tier) {
  if (tier === "weekly") return Object.keys(LIVE_LANES);
  if (tier === "pre-release") return PRE_RELEASE_LANES;
  throw new Error(`unknown tier: ${tier} (expected weekly or pre-release)`);
}

function summary(line) {
  if (process.env.GITHUB_STEP_SUMMARY) appendFileSync(process.env.GITHUB_STEP_SUMMARY, `${line}\n`);
}

async function runOne(laneName, lane, operation) {
  const key = process.env[lane.env];
  if (!key) return { lane: laneName, operation, status: "skip", reason: `${lane.env} not set` };
  const fn = lane[operation];
  if (!fn) return { lane: laneName, operation, status: "skip", reason: `lane has no ${operation} probe` };
  try {
    const out = await fn(key);
    const ok = out.httpStatus >= 200 && out.httpStatus < 300;
    return { lane: laneName, operation, status: ok ? "pass" : "fail", ...out, ...(ok ? {} : { reason: `HTTP ${out.httpStatus}` }) };
  } catch (error) {
    return { lane: laneName, operation, status: "fail", reason: redact(error?.message) };
  }
}

async function main() {
  const tier = process.env.CANARY_LIVE_TIER || "weekly";
  const laneNames = lanesForTier(tier);
  const operations = tier === "pre-release" ? ["generate", "edit"] : ["generate"];

  const results = [];
  for (const laneName of laneNames) {
    const lane = LIVE_LANES[laneName];
    if (!lane) throw new Error(`tier ${tier} names unknown lane ${laneName}`);
    for (const operation of operations) {
      results.push(await runOne(laneName, lane, operation));
    }
  }

  summary(`### Live provider canary — ${tier}`);
  summary("");
  summary("| lane | op | status | http | latency | shape |");
  summary("|---|---|---|---:|---:|---|");
  for (const r of results) {
    console.log(JSON.stringify(r));
    summary(`| ${r.lane} | ${r.operation} | ${r.status} | ${r.httpStatus ?? ""} | ${r.latencyMs ?? ""}ms | ${r.shape ?? r.reason ?? ""} |`);
  }

  const active = results.filter((r) => r.status !== "skip");
  if (active.length === 0) {
    console.log("::warning::live canary had no credentials: 0 lanes actually probed");
    summary("");
    summary("**0 lanes probed.** No canary credentials are configured, so this run proves nothing — and spent nothing.");
    return;
  }

  const failed = results.filter((r) => r.status === "fail");
  if (failed.length > 0) {
    for (const r of failed) console.error(`::error::live canary failed: ${r.lane}/${r.operation} (${r.reason})`);
    process.exit(1);
  }
}

const isMain = process.argv[1] && process.argv[1].endsWith("provider-canary-live.mjs");
if (isMain) {
  main().catch((error) => {
    console.error(`[provider-canary-live] ${redact(error?.message)}`);
    process.exit(1);
  });
}
